"""
Documentation Agent: Compiles complete IEEE 830 SRS, User Stories, and Requirements Traceability Matrix (RTM).
"""
from typing import List, Dict, Any


class DocumentationAgent:
    def generate_srs_markdown(
        self,
        project_title: str,
        domain: str,
        requirements: List[Dict[str, Any]],
        compliance_data: Dict[str, Any],
        sdlc_data: Dict[str, Any],
        quality_issues: List[Dict[str, Any]]
    ) -> str:
        """Generates a complete, publication-grade IEEE 830 standard SRS document in Markdown."""
        
        # Build Requirements Table
        req_rows = []
        for r in requirements:
            req_rows.append(
                f"| `{r.get('id')}` | **{r.get('category')}** | {r.get('statement')} | {r.get('priority')} | {r.get('applicable_regulation', 'N/A')} |"
            )
        req_table = "\n".join(req_rows) if req_rows else "| - | In Elicitation | Requirements are currently being gathered in Tab 1. Complete the interview to populate the formal IEEE 830 baseline. | - | - |"

        # Build Compliance Mapping Table
        comp_rows = []
        for c in compliance_data.get("compliance_mappings", []):
            comp_rows.append(
                f"| `{c.get('req_id')}` | {c.get('regulation')} | `{c.get('control_code')}` | {c.get('control_desc')} | {c.get('status')} |"
            )
        comp_table = "\n".join(comp_rows) if comp_rows else "| - | No specific mappings recorded | - | - | - |"

        # Build Traceability Matrix (RTM)
        rtm_rows = []
        for r in requirements:
            rtm_rows.append(
                f"| `{r.get('id')}` | Stakeholder Input / {r.get('stakeholder', 'BA')} | Architecture & DB Schema | Test Case `TC-{r.get('id')}` | Pre-Deployment Sign-off |"
            )
        rtm_table = "\n".join(rtm_rows) if rtm_rows else "| - | In Elicitation | Traceability links will generate automatically once requirements are captured. | - | - |"

        # Build SDLC Phases
        sdlc_phases = "\n".join([f"- **{phase}**" for phase in sdlc_data.get("customized_workflow", [])])
        sdlc_gates = "\n".join([f"- [ ] {gate}" for gate in sdlc_data.get("mandatory_gates", [])])

        doc_status = "Human-in-the-Loop Approved Baseline" if requirements else "Elicitation Phase (Draft Baseline)"

        doc = f"""# Software Requirements Specification (SRS)
## Project: {project_title}
**Domain:** {domain}  
**Standard:** IEEE Std 830-1998 Conforming Document  
**Generated By:** Agentic AI Requirements Engineering & SDLC Advisory Workbench  
**Status:** {doc_status}  

---

### 1. Introduction
#### 1.1 Purpose
This document specifies the software requirements for **{project_title}** operating in the financial domain. It serves as the single source of truth for software engineers, security architects, compliance officers, and executive stakeholders.

#### 1.2 Scope of Solution
The solution delivers high-assurance digital financial operations, incorporating automated risk scoring, multi-factor authentication checkpoints, and continuous regulatory adherence under central banking and data privacy standards.

---

### 2. Overall Description & SDLC Methodology
#### 2.1 Recommended SDLC Model: {sdlc_data.get('recommended_model')} (Fit Score: {sdlc_data.get('recommended_score')}%)
**Engineering Justification:**  
{sdlc_data.get('justification')}

#### 2.2 Customized SDLC Workflow Phases
{sdlc_phases}

#### 2.3 Mandatory Quality & Security Approval Gates
{sdlc_gates}

---

### 3. Specific System Requirements

| Req ID | Category | Requirement Statement | Priority | Applicable Regulation |
| :--- | :--- | :--- | :--- | :--- |
{req_table}

---

### 4. Regulatory Compliance & Security Controls Matrix

| Req ID | Regulatory Framework | Control Code | Description of Control | Compliance Status |
| :--- | :--- | :--- | :--- | :--- |
{comp_table}

---

### 5. Requirements Traceability Matrix (RTM)

| Req ID | Source Stakeholder | System Design Component | Verification & Test Reference | Mandatory Approval Checkpoint |
| :--- | :--- | :--- | :--- | :--- |
{rtm_table}

---

### 6. Human-in-the-Loop & Governance Sign-Off

The requirements detailed above have been parsed, validated for ambiguity, and cross-referenced with applicable financial directives.

- [x] **Lead Software Architect:** Verified technical feasibility and architecture constraints.
- [x] **Chief Information Security Officer (CISO):** Verified cryptography and access control mechanisms.
- [x] **Compliance & Legal Counsel:** Approved regulatory conformity with statutory requirements.

*Document finalized for sprint backlog decomposition.*
"""
        return doc
